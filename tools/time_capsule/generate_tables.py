#!/usr/bin/env python3
"""
Generate the Time Capsule data tables used by pokeemerald-expansion.

The binary source tables come from Pokemon-Gen3-to-Gen-X (MIT licensed):
  https://github.com/Lorenzooone/Pokemon-Gen3-to-Gen-X

Usage (from the repository root):
    python tools/time_capsule/generate_tables.py

The generated header is committed to the repository, so a normal build does
not need this script or the reference project. Re-run it only when the source
tables or the generator change.
"""

import hashlib
import os
import sys

# Repository root: this file lives in <root>/tools/time_capsule/.
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCE_DIR = os.path.join(ROOT, "Pokemon-Gen3-to-Gen-X", "data")
OUTPUT_H = os.path.join(ROOT, "src", "data", "time_capsule", "tables.h")
OUTPUT_C = os.path.join(ROOT, "src", "time_capsule", "gb_tables.c")

# name -> source file
TABLES = {
    "gGen1ToNatSpecies": "gen1_to_3_conv_table.bin",
    "gGen3ToGen12TextInt": "text_gen3_to_gen12_int.bin",
    "gGen12ToGen3TextInt": "text_gen12_to_gen3_int.bin",
    "gGen1Types": "pokemon_types_gen1.bin",
    "gGen2GenderKinds": "pokemon_gender.bin",
    "gGen2BaseStats": "pokemon_stats.bin",
    "gGen1BaseStats": "pokemon_stats_gen1.bin",
    "gGen12MovePp": "pokemon_moves_pp.bin",
}


def read_table(filename):
    path = os.path.join(SOURCE_DIR, filename)
    if not os.path.exists(path):
        sys.exit(
            "Missing source table: %s\n"
            "This script expects the Pokemon-Gen3-to-Gen-X reference project "
            "next to the pokeemerald-expansion repository." % path
        )
    with open(path, "rb") as f:
        data = f.read()
    return data, hashlib.sha1(data).hexdigest()


def write_array(out, storage, name, data):
    out.write("%s u8 %s[%d] = {\n" % (storage, name, len(data)))
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.write("    " + ", ".join("0x%02X" % b for b in chunk) + ",\n")
    out.write("};\n\n")


def main():
    tables = {}
    hashes = {}
    for name, filename in TABLES.items():
        tables[name], hashes[name] = read_table(filename)

    # National (1..251) -> Gen1 internal index. 0 means "not a Gen1 species".
    gen1_to_nat = tables["gGen1ToNatSpecies"]
    nat_to_gen1 = bytearray(252)
    for internal in range(1, 256):
        national = gen1_to_nat[internal]
        if 1 <= national <= 251 and nat_to_gen1[national] == 0:
            nat_to_gen1[national] = internal
    tables["gNatToGen1Species"] = bytes(nat_to_gen1)

    os.makedirs(os.path.dirname(OUTPUT_H), exist_ok=True)
    os.makedirs(os.path.dirname(OUTPUT_C), exist_ok=True)
    all_tables = list(TABLES) + ["gNatToGen1Species"]

    with open(OUTPUT_H, "w", encoding="utf-8", newline="\n") as out:
        out.write("// AUTO-GENERATED FILE - DO NOT EDIT BY HAND.\n")
        out.write("//\n")
        out.write("// Generated by: tools/time_capsule/generate_tables.py\n")
        out.write("// Run from the repository root:\n")
        out.write("//     python tools/time_capsule/generate_tables.py\n")
        out.write("//\n")
        out.write("// Source: Pokemon-Gen3-to-Gen-X/data/*.bin (MIT license),\n")
        out.write("// https://github.com/Lorenzooone/Pokemon-Gen3-to-Gen-X\n")
        out.write("//\n")
        out.write("// Source file SHA-1 checksums:\n")
        for name, filename in TABLES.items():
            out.write("//   %-40s %s\n" % (filename, hashes[name]))
        out.write("\n")
        out.write("#ifndef GUARD_TIME_CAPSULE_TABLES_H\n")
        out.write("#define GUARD_TIME_CAPSULE_TABLES_H\n\n")
        out.write('#include "global.h"\n\n')
        for name in all_tables:
            out.write("extern const u8 %s[%d];\n" % (name, len(tables[name])))
        out.write("\n#endif // GUARD_TIME_CAPSULE_TABLES_H\n")

    with open(OUTPUT_C, "w", encoding="utf-8", newline="\n") as out:
        out.write("// AUTO-GENERATED FILE - DO NOT EDIT BY HAND.\n")
        out.write("// Generated by tools/time_capsule/generate_tables.py.\n")
        out.write("// Definitions live here so the tables are emitted once, not in\n")
        out.write("// every translation unit that includes tables.h.\n\n")
        out.write('#include "global.h"\n')
        out.write('#include "../data/time_capsule/tables.h"\n\n')
        for name in all_tables:
            write_array(out, "const", name, tables[name])
        out.write("// End of generated tables.\n")

    print("Wrote %s and %s" % (OUTPUT_H, OUTPUT_C))


if __name__ == "__main__":
    main()
